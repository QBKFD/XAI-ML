#!/usr/bin/env bash
# Install the three rule learners that no longer install with a plain `pip install`.
#
#   MDL     rulelist 0.2.0   metadata pins scikit-learn==0.23 -> install with --no-deps
#   IDS     pyIDS + pyarc    not on PyPI / declares the defunct `sklearn` package
#   CORELS  corels 1.1.29    setup.py breaks on Python >= 3.11 and numpy 2
#
# The runtime incompatibilities of rulelist and pyIDS with current pandas/numpy
# are handled in xai/compat.py, so nothing is pinned to old versions.
#
# Usage:  bash scripts/install_legacy_deps.sh            (uses `python` on PATH)
#         PYTHON=.venv/bin/python bash scripts/install_legacy_deps.sh
#         SKIP_CORELS=1 bash scripts/install_legacy_deps.sh   (no C++ compiler)

set -euo pipefail

PYTHON="${PYTHON:-python}"
PYIDS_COMMIT="bc0ca88dc3dee3e33d203dced9c696620a5fcc55"
CORELS_SDIST_URL="https://files.pythonhosted.org/packages/c8/a9/2817e6f465f36ade1fc3a3d29fd8af299bb4fac137ea0885a52259121eb8/corels-1.1.29.tar.gz"
CORELS_SDIST_SHA256="a58c33674b337278897d8fa47953a74878660f58b238522048656531df8f3c19"

pip_install() { "$PYTHON" -m pip install --disable-pip-version-check "$@"; }

echo "==> MDL (rulelist) and its runtime dependencies"
pip_install "gmpy2>=2.1" "numba>=0.58"
pip_install --no-deps "rulelist==0.2.0"

echo "==> IDS (pyIDS, pyarc, pyfim)"
pip_install "pyfim>=6.28" requests
pip_install --no-deps "pyarc==1.1.4"
pip_install --no-deps "pyids @ git+https://github.com/jirifilip/pyIDS.git@${PYIDS_COMMIT}"

if [[ "${SKIP_CORELS:-0}" == "1" ]]; then
  echo "==> Skipping CORELS (SKIP_CORELS=1)"
  exit 0
fi

echo "==> CORELS (patched build from source)"
pip_install setuptools wheel "cython>=3"
workdir="$(mktemp -d)"
trap 'rm -rf "$workdir"' EXIT

# Download the PyPI source release (it bundles the C++ core, unlike the GitHub
# repo, which uses a submodule), verify it, and patch it. Python is used
# instead of curl/sed so the script behaves the same on macOS and Linux.
"$PYTHON" - "$workdir" "$CORELS_SDIST_URL" "$CORELS_SDIST_SHA256" <<'PY'
import hashlib, pathlib, sys, tarfile, urllib.request
workdir, url, sha = pathlib.Path(sys.argv[1]), sys.argv[2], sys.argv[3]
archive = workdir / "corels.tar.gz"
with urllib.request.urlopen(url) as r:
    archive.write_bytes(r.read())
if hashlib.sha256(archive.read_bytes()).hexdigest() != sha:
    sys.exit("corels sdist checksum mismatch")
with tarfile.open(archive) as tar:
    try:
        tar.extractall(workdir, filter="data")
    except TypeError:  # Python < 3.10.12 has no extraction filters
        tar.extractall(workdir)
root = workdir / "pycorels"
(workdir / "corels-1.1.29").rename(root)

setup = root / "setup.py"
s = setup.read_text()
# __builtins__ is a dict when setup.py is run by modern build frontends.
s = s.replace("__builtins__.__NUMPY_SETUP__ = False", "pass")
# Build without GMP: it only speeds up bit vectors, and the bare try/except
# fallback in setup.py does not trigger reliably.
s = s.replace("install(True)", "install(False)")
setup.write_text(s)

utils = root / "corels" / "utils.py"
u = utils.read_text()
u = u.replace("np.array(x, order='C', copy=False)", "np.asarray(x, order='C')")
utils.write_text(u)

corels_py = root / "corels" / "corels.py"
c = corels_py.read_text().replace("dtype=np.bool)", "dtype=bool)")
corels_py.write_text(c)
PY

# The shipped C++ file was generated by an old Cython; regenerate it.
( cd "$workdir/pycorels" && "$PYTHON" -m cython --cplus -3 corels/_corels.pyx -o corels/_corels.cpp )
SETUPTOOLS_USE_DISTUTILS=local pip_install --no-build-isolation "$workdir/pycorels"

echo "==> Checking imports"
echo "    (pip may have reported dependency conflicts for rulelist/pyarc above."
echo "     Those come from their outdated metadata and are expected.)"
"$PYTHON" - <<'PY'
from xai.models import MODELS
for key, cls in MODELS.items():
    missing = cls.missing_dependencies()
    print(f"  {key:<14} {'ok' if not missing else 'missing: ' + ', '.join(missing)}")
PY
